            </li>

            <li>
                <h5>Nginx:</h5>  <p>A high-performance web server and reverse proxy that serves web traffic quickly.</p>
            </li>

            <li>
                <h5>PHP:</h5>  <p>A server-side scripting language used to build dynamic websites and web apps.</p>
            </li>

            <li>
                <h5>MySQL:</h5>  <p>A database system that stores and organizes app data.</p>
