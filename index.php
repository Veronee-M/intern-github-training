            </li>

            <li>
                <h5>Integrated terminal:</h5>  <p>A built-in command-line window that runs commands directly inside the editor.</p>
            </li>

            <li>
                <h5>File explorer:</h5>  <p>A side panel that shows and organizes all folders and files in a project.</p>
            </li>

            <li>
                <h5>Source Control panel:</h5>  <p> A built-in tab that manages Git tasks like commits, diffs, and pushes.</p>
            </li>

            <li>
                <h5>Command Palette:</h5>  <p>A searchable menu that gives fast access to all editor commands and settings.</p>
            </li>
        </ul>


