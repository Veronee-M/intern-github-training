    <div class= "github" id="github-section">
        <h2>GitHub</h2>
        <p>GitHub is a platform for building software. GitHub is a platform that lets you manage code, 
            coordinate team updates, and explore shared projects to learn from real examples. 
            GitHub brings together the tools and workflows you need across every stage of the 
            software development life cycle
        </p>

        <h3>Key Terms</h3>
        <ul>
            <li>
                <h5>Repository:</h5>  <p>A storage folder for a project where all files and version history are kept.</p>
            </li>

            <li>
                <h5>Commit:</h5>  <p>A saved snapshot of changes made to files in a project.</p>
            </li>

            <li>
                <h5>Push:</h5>  <p>Uploading local commits to a remote repository on GitHub.</p>
            </li>

            <li>
                <h5>Pull:</h5>  <p>Downloading the newest changes from a remote repository to a local machine.</p>
            </li>

            <li>
                <h5>Clone:</h5>  <p>Creating a full local copy of an existing remote repository.</p>
            </li>

            <li>
                <h5>Branch:</h5>  <p>A separate workspace copy of the code used to test changes safely without breaking the main project. </p>
            </li>

            <li>
                <h5>Merge:</h5>  <p>Combining changes from one branch into another.</p>
            </li>

            <li>
                <h5>Pull Request:</h5>  <p>A formal request to review and merge code changes into a main branch.</p>
            </li>

            <li>
                <h5>.gitignore:</h5>  <p>A text file that tells Git which files or folders to ignore and not track.</p>
            </li>

            <li>
                <h5>README:</h5>  <p>A markdown text file that explains what the project is, how to install it, and how to use it.</p>
            </li>


        </ul>

    </div>
    
    





